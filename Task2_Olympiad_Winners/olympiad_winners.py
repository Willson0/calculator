"""Определение, вошёл ли участник в тройку лидеров олимпиады.

На сервере сломался общий рейтинг, остался только неотсортированный
список баллов. По условию все баллы разные, больше балл — лучше результат.
"""


def check_winners(scores, student_score):
    """Печатает, входит ли балл участника в тройку лидеров.

    Стас в тройке, если меньше трёх участников набрали больше его балла.
    Функция ничего не возвращает — только печатает сообщение.

    Args:
        scores (list[int | float]): Баллы всех участников олимпиады.
        student_score (int | float): Балл участника, которого проверяем.

    Example:
        >>> check_winners([20, 48, 52, 38], 48)
        Вы в тройке победителей!
    """
    # Сколько участников набрали больше, чем Стас
    better_results = sum(score > student_score for score in scores)

    # Если впереди меньше трёх человек, Стас в тройке лидеров
    if better_results < 3:
        print("Вы в тройке победителей!")
    else:
        print("Вы не попали в тройку победителей.")


if __name__ == "__main__":
    check_winners([20, 48, 52, 38, 36, 13, 7, 41, 34, 24, 5, 51], 48)
