"""Расфасовка пирожных по коробкам на 3 и 5 штук.

Кондитерская хочет знать, какие количества пирожных можно без остатка
разложить по коробкам на 3 или на 5 штук.
"""


def print_pack_report(count):
    """Печатает отчёт о расфасовке для всех чисел от count до 1.

    Для каждого числа выводится:
    - ``число - расфасуем по 3 или по 5``, если делится и на 3, и на 5;
    - ``число - расфасуем по 5``, если делится только на 5;
    - ``число - расфасуем по 3``, если делится только на 3;
    - ``число - не заказываем!`` во всех остальных случаях.

    Args:
        count (int): Целое положительное число больше единицы.

    Raises:
        ValueError: Если count не целое число больше единицы.

    Example:
        >>> print_pack_report(3)
        3 - расфасуем по 3
        2 - не заказываем!
        1 - не заказываем!
    """
    if not isinstance(count, int) or count <= 1:
        raise ValueError("Нужно целое число больше единицы")

    # Перебираем числа в порядке убывания: от count до 1
    for number in range(count, 0, -1):
        divisible_by_3 = number % 3 == 0
        divisible_by_5 = number % 5 == 0

        if divisible_by_3 and divisible_by_5:
            print(f"{number} - расфасуем по 3 или по 5")
        elif divisible_by_5:
            print(f"{number} - расфасуем по 5")
        elif divisible_by_3:
            print(f"{number} - расфасуем по 3")
        else:
            print(f"{number} - не заказываем!")


if __name__ == "__main__":
    print_pack_report(int(input("Сколько пирожных в поставке? ")))
